package main

import (
	"fmt"
	"net/http"
	"slices"
	"time"

	json "encoding/json/v2"

	"github.com/chew-z/web_search/internal/oauth"
	"github.com/mark3labs/mcp-go/server"
)

// HTTP server timeouts to mitigate Slowloris-style DoS attacks.
const (
	httpReadTimeout  = 30 * time.Second
	httpWriteTimeout = 15 * time.Minute // must accommodate the longest web-search (timeoutXHigh = 15m)
	httpIdleTimeout  = 120 * time.Second
)

// RunStdioTransport runs the MCP server using STDIO transport.
func RunStdioTransport(mcpServer *server.MCPServer) error {
	Info("transport listening", "protocol", "stdio")
	return server.ServeStdio(mcpServer)
}

// RunHTTPTransport runs the MCP server using Streamable HTTP transport.
//
// The MCP handler is mounted at "/" (catch-all) so the server works behind
// reverse proxies that forward the original request URI (e.g. nginx with
// variable proxy_pass sends /answer/mcp, not /mcp). The mcp-go
// StreamableHTTPServer routes by method, not path, so a catch-all mount is
// safe and correct; the exact OAuth, health, and capabilities routes below
// take precedence over it in the ServeMux.
//
// When cfg.AuthEnabled is true, the MCP handler is wrapped with the authGuard,
// which validates JWT Bearer tokens at the HTTP layer and returns HTTP 401
// with a WWW-Authenticate challenge before any MCP handshake occurs. Legacy
// tokens generated by GeminiMCP with the same secret key are accepted without
// modification.
//
// When cfg.OAuthEnabled is true, the OAuth 2.1 authorization server
// (discovery metadata, /authorize, /login, /token, /register) is mounted
// beside the MCP endpoint, and the guard additionally accepts OAuth access
// tokens and advertises resource_metadata in its 401 challenges so claude.ai
// connectors can start the browser login flow.
//
// When cfg.Heartbeat > 0 the server sends periodic SSE heartbeat pings on
// streaming connections — important for long-running web-search requests that
// would otherwise be silently dropped by proxies or load balancers.
func RunHTTPTransport(mcpServer *server.MCPServer, cfg MCPConfig) error {
	var mcpOpts []server.StreamableHTTPOption

	if cfg.Heartbeat > 0 {
		Debug("heartbeat configured", "interval", cfg.Heartbeat)
		mcpOpts = append(mcpOpts, server.WithHeartbeatInterval(cfg.Heartbeat))
	}

	// Disable DNS rebinding protection — the server runs on remote hosts
	// behind reverse proxies, not on localhost. Controlled by config;
	// defaults to true (protection off) since production deployments
	// always sit behind nginx.
	if cfg.DisableLocalhostProtection {
		mcpOpts = append(mcpOpts, server.WithDisableLocalhostProtection(true))
	}

	mcpOpts = append(mcpOpts, server.WithStreamableHTTPLogger(SLogger()))

	mcpHandler := server.NewStreamableHTTPServer(mcpServer, mcpOpts...)

	var oauthCfg *oauth.Config
	if cfg.OAuthEnabled {
		derived, err := cfg.OAuthConfig()
		if err != nil {
			return fmt.Errorf("build OAuth configuration: %w", err)
		}
		oauthCfg = &derived
	}

	// A nil guard means open mode; protectMCP passes requests through.
	var guard *authGuard
	if cfg.AuthEnabled {
		guard = newAuthGuard(cfg.AuthSecretKey, oauthCfg)
		Info("auth enabled", "method", "JWT/HS256", "oauth", cfg.OAuthEnabled)
	}

	mux := http.NewServeMux()
	mux.Handle("/", guard.protectMCP(mcpHandler))
	mux.HandleFunc("/health", handleHealth)
	mux.HandleFunc("/capabilities", handleCapabilities(mcpServer, cfg))
	if oauthCfg != nil {
		oauth.Mount(mux, *oauthCfg, oauth.NewStore(nil), SLogger())
		Info("oauth mounted", "issuer", oauthCfg.Issuer, "resource", oauthCfg.Resource)
	}

	addr := fmt.Sprintf("%s:%s", cfg.Host, cfg.Port)
	Info("transport listening", "protocol", "http", "addr", addr, "endpoint", fmt.Sprintf("http://%s/", addr))

	srv := &http.Server{
		Addr:         addr,
		Handler:      mux,
		ReadTimeout:  httpReadTimeout,
		WriteTimeout: httpWriteTimeout,
		IdleTimeout:  httpIdleTimeout,
	}
	return srv.ListenAndServe()
}

// handleHealth answers liveness probes; it is deliberately unauthenticated
// so nginx and monitoring can reach it without credentials.
func handleHealth(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet {
		http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
		return
	}
	respondJSON(w, http.StatusOK, map[string]any{
		"status":    "healthy",
		"timestamp": time.Now().UTC().Format(time.RFC3339),
		"service":   serverName,
	})
}

// handleCapabilities serves tool and auth discovery for operators; like
// /health it is unauthenticated and advertises only public metadata.
func handleCapabilities(mcpServer *server.MCPServer, cfg MCPConfig) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodGet {
			http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
			return
		}
		respondJSON(w, http.StatusOK, map[string]any{
			"name":        serverName,
			"version":     serverVersion,
			"description": "MCP server for deep-reasoning web search",
			"transport":   "http",
			"tools":       capabilityTools(mcpServer),
			"authentication": map[string]any{
				"enabled": cfg.AuthEnabled,
				"type":    "bearer",
				"oauth":   cfg.OAuthEnabled,
			},
			"features": []string{"web_search", "health_check", "capabilities_discovery"},
		})
	}
}

// capabilityTools returns deterministic capability data for the registered MCP tools.
func capabilityTools(s *server.MCPServer) []map[string]any {
	tools := make([]map[string]any, 0)
	if s == nil {
		return tools
	}

	registered := s.ListTools()
	names := make([]string, 0, len(registered))
	for name := range registered {
		names = append(names, name)
	}
	slices.Sort(names)

	for _, name := range names {
		serverTool := registered[name]
		tool := serverTool.Tool
		inputSchema := any(tool.InputSchema)
		if len(tool.RawInputSchema) > 0 {
			inputSchema = tool.RawInputSchema
		}
		tools = append(tools, map[string]any{
			"name":        tool.Name,
			"description": tool.Description,
			"inputSchema": inputSchema,
		})
	}

	return tools
}

// respondJSON marshals value and writes it with the supplied status. The name
// avoids the writeJSON test helper in api_test.go, which takes a *testing.T.
func respondJSON(w http.ResponseWriter, status int, value any) {
	body, err := json.Marshal(value)
	if err != nil {
		http.Error(w, "", http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_, _ = w.Write(body)
}
